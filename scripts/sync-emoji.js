#!/usr/bin/env node
/**
 * Writes editor/assets/js/chars/emoji-core.js from Vanilla Breeze's curated
 * emoji (src/data/emoji-data.js): 209 emoji with names and keywords, and
 * their 43 alias shortcodes. VB's published build bundles this list inside
 * <emoji-picker> without exporting it; its full gemoji list is published
 * (dist/cdn/emoji-extended.js) and loads at runtime (chars/emoji-index.js).
 *
 * Run after updating vanilla-breeze: node scripts/sync-emoji.js [path-to-vb]
 */
import { writeFileSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const vb = resolve(process.argv[2] || join(root, '..', 'vanilla-breeze'));
const { EMOJI_MAP, EMOJI_ALIASES } = await import(pathToFileURL(join(vb, 'src', 'data', 'emoji-data.js')).href);

const rows = [...EMOJI_MAP.values()].map((e) => [e.shortcode, e.emoji, e.name, e.group, e.keywords || []]);
const aliases = [...EMOJI_ALIASES.entries()];
const out = `/**
 * Vanilla Breeze's curated emoji: [shortcode, emoji, name, group, keywords]
 * and alias shortcodes. Generated by scripts/sync-emoji.js — do not edit.
 * @module editor/chars/emoji-core
 */
export const CORE_EMOJI = ${JSON.stringify(rows)};
export const CORE_ALIASES = ${JSON.stringify(aliases)};
`;
writeFileSync(join(root, 'editor', 'assets', 'js', 'chars', 'emoji-core.js'), out);
console.log(`emoji-core.js: ${rows.length} emoji, ${aliases.length} aliases`);
